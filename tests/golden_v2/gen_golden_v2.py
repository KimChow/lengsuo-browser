#!/usr/bin/env python3
"""Independent golden-v2 profile fixture generator (W7, tests-only).

Builds the canonical 148-byte schema-2 LBPF1 stream from the EXPLICIT FAKE
FIELD DICTIONARY below -- never by reading, patching, or splicing the frozen
v1 fixture (native/golden.inc). This file and the Rust producer encoder are
two independent constructions of the same value dictionary; byte-for-byte
agreement between them is the cross-check that freezes the golden. Do not
"fix" a mismatch by editing one side's bytes -- fix the encoder, or change
the dictionary deliberately and refreeze both sides.

Layout (schema 2; schema 1 is this stream minus the policy byte, every v1
offset unchanged, and v1's golden.inc stays exactly as frozen):
    magic "LBPF1"                 5 x u8
    schema_version                u32 = 2
    noise_version                 u32 = 1
    environment_id                TEXT(id): u16 len + [A-Za-z0-9-_], nonempty
    pool_version                  TEXT(id)
    noise_seed                    8 x u8
    platform                      u8 in 0..4
    width, height                 u32, <=16384 each, product <= 64 Mi
    color_depth                   u8 in {8,24,30}
    dpr_milli                     u32 in 1..10000
    cpu_cores                     u16 in 1..1024
    memory_mib                    u32 in 128..1048576
    max_touch_points              u8 <= 10, nonzero on Android(3)/iOS(4)
    language                      TEXT: u16 len + printable, <=35, nonempty
    timezone                      TEXT: u16 len + printable, <=64, nonempty
    webrtc_ip_handling_policy     u8 in 0..3   <-- schema 2 only, HERE:
                                  after timezone, before slot_count
    slot_count                    u16 = 7
    slots                         7 x (TEXT(name,id,<=12) + u32 in 1..1048576)
                                  canonical order: audio, canvas,
                                  client_rects, fonts, gpu, ua, webgl
    (no trailing bytes; decoder End() is strict)

Provenance discipline (mirrors native/VERIFICATION.md for the v1 147-byte
golden): native/golden_v2.inc is a PROPOSAL generated by this script until
the Rust producer independently encodes the same dictionary and agrees byte
for byte; then it is frozen and referenced by the C++ decoder test
(native/golden_v2_decoder_test.cc), which asserts these bytes decode to the
dictionary below before any mutation cases.

Usage:
    python3 -I tests/golden_v2/gen_golden_v2.py            # verify + print
    python3 -I tests/golden_v2/gen_golden_v2.py --write    # rewrite .inc
"""

import sys
from pathlib import Path

MAX_STREAM = 4096
SLOT_NAMES = ["audio", "canvas", "client_rects", "fonts", "gpu", "ua", "webgl"]

# The explicit fake field dictionary (example values for fixture purposes
# only; no real profile). Field content deliberately mirrors the sizes used
# in the v1 golden's framing so the schema-2 stream is exactly 148 bytes and
# version-branch prefix checks stay offset-stable; the CONTENT construction
# path here is fully independent of golden.inc.
FIELDS = {
    "schema_version": 2,
    "noise_version": 1,
    "environment_id": "env-1",
    "pool_version": "p1",
    "noise_seed": [0, 1, 2, 3, 4, 5, 6, 7],
    "platform": 0,                   # Windows
    "width": 1920,
    "height": 1080,
    "color_depth": 24,
    "dpr_milli": 1000,
    "cpu_cores": 8,
    "memory_mib": 8192,
    "max_touch_points": 0,
    "language": "en-US",
    "timezone": "UTC",
    "webrtc_ip_handling_policy": 2,  # kDefaultPublicInterfaceOnly
    "slot_count": 7,
    "slots": {"audio": 3, "canvas": 1, "client_rects": 5, "fonts": 4,
              "gpu": 6, "ua": 7, "webgl": 2},
}


def u(n, width):
    assert 0 <= n < (1 << (8 * width)), n
    return list(n.to_bytes(width, "big"))


def text(value, identifier=False, max_len=64):
    data = value.encode("ascii")
    assert 0 < len(data) <= max_len, value
    for c in data:
        assert 32 <= c <= 126, value
        if identifier:
            assert chr(c).isalnum() or c in (0x2D, 0x5F), value
    return u(len(data), 2) + list(data)


def validate(f, lenient_policy=False):
    assert f["schema_version"] in (1, 2)
    assert f["noise_version"] == 1
    assert len(f["noise_seed"]) == 8
    p = f["platform"]
    assert p <= 4
    assert 1 <= f["width"] <= 16384 and 1 <= f["height"] <= 16384
    assert f["width"] * f["height"] <= 64 * 1048576
    assert f["color_depth"] in (8, 24, 30)
    assert 1 <= f["dpr_milli"] <= 10000
    assert 1 <= f["cpu_cores"] <= 1024
    assert 128 <= f["memory_mib"] <= 1048576
    assert f["max_touch_points"] <= 10
    assert p not in (3, 4) or f["max_touch_points"] != 0
    assert f["slot_count"] == len(SLOT_NAMES)
    assert sorted(f["slots"]) == sorted(SLOT_NAMES)
    assert all(1 <= v <= 1048576 for v in f["slots"].values())
    if f["schema_version"] == 2 and not lenient_policy:
        assert f["webrtc_ip_handling_policy"] <= 3


def build(f, lenient_policy=False):
    """Encode per schema_version; schema 1 omits the policy byte entirely.
    lenient_policy allows an out-of-range policy byte (mutation cases only)."""
    validate(f, lenient_policy)
    out = list(b"LBPF1")
    out += u(f["schema_version"], 4)
    out += u(f["noise_version"], 4)
    out += text(f["environment_id"], identifier=True)
    out += text(f["pool_version"], identifier=True)
    out += [b % 256 for b in f["noise_seed"]]
    out += u(f["platform"], 1)
    out += u(f["width"], 4)
    out += u(f["height"], 4)
    out += u(f["color_depth"], 1)
    out += u(f["dpr_milli"], 4)
    out += u(f["cpu_cores"], 2)
    out += u(f["memory_mib"], 4)
    out += u(f["max_touch_points"], 1)
    out += text(f["language"], max_len=35)
    out += text(f["timezone"], max_len=64)
    if f["schema_version"] == 2:
        out += u(f["webrtc_ip_handling_policy"], 1)
    out += u(f["slot_count"], 2)
    for name in SLOT_NAMES:
        out += text(name, identifier=True, max_len=12)
        out += u(f["slots"][name], 4)
    assert len(out) <= MAX_STREAM
    return out


def variants(base):
    """Named mutation streams for cross-checking the C++ decoder tests.
    Each is a complete encode from a dictionary that differs from `base` in
    exactly one respect -- never a splice of another fixture's bytes."""
    out = {}
    full = build(base)
    for p in (0, 1, 2, 3):
        out[f"ok_policy_{p}"] = build(
            {**base, "webrtc_ip_handling_policy": p})
    for v in (0, 3, 4, 0xFFFFFFFF):
        # Wrong version inside an otherwise-valid v2 frame: encode leniently
        # by patching only the u32 version field of a fresh full encode
        # (this is the version field, a designated 4-byte slot, not a
        # layout splice of the v1 fixture).
        b = build(base)
        b[5:9] = u(v, 4)
        out[f"bad_version_{v}"] = b
    for p in (4, 255):
        out[f"bad_policy_{p}"] = build(
            {**base, "webrtc_ip_handling_policy": p}, lenient_policy=True)
    # Truncated schema 2: same dictionary encoded with the policy byte
    # omitted from the output section (schema_version stays 2).
    # kTzEnd = 65 (prefix through timezone), policy byte at 65, slots at 66.
    out["truncated_v2"] = full[:65] + full[66:]
    # Policy byte duplicated (extra byte before the slot table).
    out["policy_duplicated"] = full[:66] + [full[65]] + full[66:]
    # Trailing byte after the slot table (End() must be strict).
    out["trailing"] = full + [0]
    # v1 stream from the same dictionary: schema 1 decodes with no policy.
    out["schema1"] = build({**base, "schema_version": 1})
    return out


def render_inc(data, name):
    lines, per = [], 37
    for i in range(0, len(data), per):
        lines.append(",".join(str(b) for b in data[i:i + per]))
    body = "    " + ",\n    ".join(lines)
    return ("// Golden schema-2 LBPF1 stream: %d bytes from the explicit fake\n"
            "// field dictionary in tests/golden_v2/gen_golden_v2.py, with\n"
            "// webrtc_ip_handling_policy=%d after timezone, before slot_count.\n"
            "// GENERATED independently, not patched from v1. Python and the Rust\n"
            "// TEST encoder reproduce these bytes. Production Rust API integration\n"
            "// and browser policy injection remain separate pending work.\n"
            "// v1 golden.inc stays unchanged.\n"
            "constexpr unsigned char %s[] = {\n%s\n};\n"
            % (len(data), FIELDS["webrtc_ip_handling_policy"], name, body))


def main():
    data = build(FIELDS)
    v1 = build({**FIELDS, "schema_version": 1})
    assert len(v1) == 147, len(v1)
    assert len(data) == 148, len(data)
    tz_end = 5 + 4 + 4 + (2 + 5) + (2 + 2) + 8 + 1 + 4 + 4 + 1 + 4 + 2 + 4 \
        + 1 + (2 + 5) + (2 + 3)
    # Version-branch layout proof: magic agrees, and every byte from the end
    # of schema_version through the end of timezone agrees. The schema_version
    # u32 at [5, 9) is the only intended difference in the shared prefix --
    # asserting equality over it would compare 2 against 1 and always fail.
    assert data[:5] == v1[:5]
    assert data[5:9] == u(2, 4) and v1[5:9] == u(1, 4)
    assert data[9:tz_end] == v1[9:tz_end]
    assert data[tz_end] == FIELDS["webrtc_ip_handling_policy"]
    assert data[tz_end + 1:] == v1[tz_end:]
    assert tz_end == 65, tz_end
    print(f"schema2 bytes = {len(data)}")
    print("hex: " + bytes(data).hex())
    for name, stream in variants(FIELDS).items():
        print(f"variant {name}: {len(stream)} bytes")
    target = Path(__file__).resolve().parents[2] / "native" / "golden_v2.inc"
    if "--write" in sys.argv:
        target.write_text(render_inc(data, "kGoldenV2"))
        print(f"wrote {target}")
    else:
        print(f"(dry run; --write would update {target})")


if __name__ == "__main__":
    main()
